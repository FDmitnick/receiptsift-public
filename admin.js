document.querySelector("#paymentsBody").addEventListener("click", async (event) => {
  const refundButton = event.target.closest("[data-refund]");
  if (refundButton) {
    const payment = state.payments.get(refundButton.dataset.refund);
    const available = Number(payment.amount_value) - Number(payment.refunded_amount || 0);
    document.querySelector("#refundForm").dataset.paymentId = payment.provider_payment_id;
    renderRefundPaymentLabel(payment);
    document.querySelector("#refundAmount").value = available.toFixed(2);
    document.querySelector("#refundReason").value = "";
    document.querySelector("#refundConfirmation").value = "";
    refundDialog.showModal();
    return;
  }
  const cancelButton = event.target.closest("[data-cancel]");
  if (!cancelButton) return;
  const reason = prompt(t("Reason for cancelling future PayPal renewals:"), t("Cancelled after owner review"));
  if (!reason) return;
  const confirmation = prompt(t("Type CANCEL to stop future renewals. This does not refund past payments."));
  if (confirmation !== "CANCEL") { message.textContent = t("Cancellation was not confirmed."); return; }
  const password = document.querySelector("#ownerActionPassword").value;
  if (!password) { message.textContent = t("Enter the owner password before a payment action."); return; }
  try {
    await request(`/api/admin/subscriptions/${encodeURIComponent(cancelButton.dataset.cancel)}/cancel`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ reason, confirmation, password }) });
    document.querySelector("#ownerActionPassword").value = "";
    message.textContent = t("Subscription cancellation accepted by PayPal.");
    await loadPayments();
  } catch (error) { message.textContent = error.message; }
});

document.querySelector("#refundForm").addEventListener("submit", async (event) => {
  event.preventDefault();
  const payment = state.payments.get(event.currentTarget.dataset.paymentId);
  const payload = { amount: document.querySelector("#refundAmount").value, currency: payment.currency, reason: document.querySelector("#refundReason").value, confirmation: document.querySelector("#refundConfirmation").value, password: document.querySelector("#ownerActionPassword").value };
  if (!payload.password) { message.textContent = t("Enter the owner password before a payment action."); return; }
  try {
    await request(`/api/admin/payments/${encodeURIComponent(payment.provider_payment_id)}/refund`, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(payload) });
    document.querySelector("#ownerActionPassword").value = "";
    refundDialog.close(); message.textContent = t("Refund sent to PayPal and recorded.");
    await loadPayments();
  } catch (error) { message.textContent = error.message; }
});

