    await request(`/api/admin/diagnostic-cases/${encodeURIComponent(state.diagnosticCaseId)}`, { method: "DELETE" });
    diagnosticDetailDialog.close();
    state.diagnosticCaseId = null;
    state.diagnosticDetail = null;
    message.textContent = t("Diagnostic case deleted.");
    await loadDiagnostics();
