async function request(path, options = {}) {
  let response;
  try { response = await fetch(path, options); }
  catch (_) { throw new Error(state.language === "zh" ? "无法连接 ReceiptSift，请稍后重试。" : "Unable to connect to ReceiptSift. Try again."); }
  if (response.status === 401) location.replace(`/login?next=${encodeURIComponent(location.pathname)}`);
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) throw new Error(apiErrorMessage(payload.error?.code, payload.error?.message, t("The operation failed.")));
  return payload;
}

function statusPill(status) {
  const value = String(status || "UNKNOWN").toUpperCase();
  const tone = ["ACTIVE", "COMPLETED"].includes(value)
    ? "ok"
    : ["PENDING", "REFUND_PENDING", "APPROVAL_PENDING"].includes(value)
      ? "warn"
      : ["DENIED", "FAILED", "REVERSED", "SUSPENDED"].includes(value)
        ? "bad"
        : "";
  const label = state.language === "zh" ? (statusCopy[value] || value.replaceAll("_", " ")) : value.replaceAll("_", " ");
  return `<span class="pill ${tone}">${escapeHtml(label)}</span>`;
}

const PAGE_SIZE = 15;

function pageSlice(items, key) {
  const totalPages = Math.max(1, Math.ceil(items.length / PAGE_SIZE));
  state.pagination[key] = Math.min(Math.max(1, state.pagination[key] || 1), totalPages);
  const start = (state.pagination[key] - 1) * PAGE_SIZE;
  return { rows: items.slice(start, start + PAGE_SIZE), totalPages };
}

function renderPagination(key, total, totalPages) {
  const footer = document.querySelector(`#${key}Pagination`);
  const current = state.pagination[key];
  footer.classList.toggle("hidden", total === 0);
  footer.innerHTML = total === 0 ? "" : `<span>${state.language === "zh" ? `共 ${total} 条，第 ${current}/${totalPages} 页` : `${total} records, page ${current} of ${totalPages}`}</span><div><button type="button" data-page-key="${key}" data-page-delta="-1" ${current <= 1 ? "disabled" : ""}>${t("Previous")}</button><button type="button" data-page-key="${key}" data-page-delta="1" ${current >= totalPages ? "disabled" : ""}>${t("Next")}</button></div>`;
}

function syncCurrentQuery() {
  const params = new URLSearchParams();
  if (["overview", "traffic"].includes(state.page) && state.days !== 30) params.set("days", String(state.days));
  if (state.page === "users" && document.querySelector("#userSearch").value) params.set("search", document.querySelector("#userSearch").value);
  if (state.page === "traffic" && document.querySelector("#eventFilter").value) params.set("event", document.querySelector("#eventFilter").value);
  const query = params.toString();
  history.replaceState(null, "", `${location.pathname}${query ? `?${query}` : ""}`);
}

