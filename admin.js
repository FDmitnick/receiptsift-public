async function loadCurrentPage() {
  message.classList.remove("error");
  message.textContent = t("Refreshing operations data…");
  try {
    await pageLoaders[state.page]();
    message.textContent = state.language === "zh" ? `更新于 ${new Date().toLocaleTimeString(locale())}` : `Updated ${new Date().toLocaleTimeString(locale())}`;
  } catch (error) {
    message.classList.add("error");
    message.textContent = error.message;
  }
}

