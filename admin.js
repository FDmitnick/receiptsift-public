function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>'"]/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" })[character]);
}

function date(value) {
  if (!value) return "-";
  return new Date(value).toLocaleString(locale(), { month: "short", day: "numeric", year: "numeric", hour: "numeric", minute: "2-digit" });
}

function money(value, currency = "USD") {
  return new Intl.NumberFormat(locale(), { style: "currency", currency }).format(Number(value || 0));
}

function integer(value) {
  return new Intl.NumberFormat(locale(), { maximumFractionDigits: 0 }).format(Number(value || 0));
}

function percentage(value) {
  return new Intl.NumberFormat(locale(), { style: "percent", maximumFractionDigits: 0 }).format(Math.max(0, Number(value || 0)));
}

function periodDelta(current, previous) {
  const currentValue = Number(current || 0);
  const previousValue = Number(previous || 0);
  if (currentValue === previousValue) return { label: t("No change"), tone: "flat" };
  if (previousValue === 0) return { label: t("New this period"), tone: "up" };
  const change = Math.round(((currentValue - previousValue) / Math.abs(previousValue)) * 100);
  return {
    label: `${change > 0 ? "+" : ""}${change}% ${t("vs prior period")}`,
    tone: change > 0 ? "up" : "down",
  };
}

function dailyBuckets(rows, maxPoints = 45) {
  const values = Array.isArray(rows) ? rows : [];
  if (values.length <= maxPoints) return values;
  const size = Math.ceil(values.length / maxPoints);
  const numericKeys = ["visitors", "registrations", "documents_parsed", "page_views", "csv_exports", "processed_images", "total_tokens", "ai_calls", "estimated_cost_usd"];
  const buckets = [];
  for (let index = 0; index < values.length; index += size) {
    const group = values.slice(index, index + size);
    const item = { date: group[group.length - 1].date };
    numericKeys.forEach((key) => { item[key] = group.reduce((sum, row) => sum + Number(row[key] || 0), 0); });
    buckets.push(item);
  }
  return buckets;
}

function chartDate(value) {
  const parsed = new Date(`${value}T00:00:00Z`);
  return parsed.toLocaleDateString(locale(), { month: "short", day: "numeric", timeZone: "UTC" });
}

